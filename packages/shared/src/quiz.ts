/** Взять случайный промпт, не повторяясь; когда банк исчерпан — начинаем заново. */
export function pickQuizPrompt(usedIds: string[] = []): QuizPrompt {
  let pool = QUIZ_PROMPTS.filter((p) => !usedIds.includes(p.id));
  if (pool.length === 0) pool = QUIZ_PROMPTS;
  return pool[Math.floor(Math.random() * pool.length)];
}
